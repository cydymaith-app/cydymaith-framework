"""Builds a project into a static site.

python3 build.py [OUTDIR]                    write the site to OUTDIR (default: dist)
python3 build.py [OUTDIR] --project DIR      choose the project (default: the only folder in ./content/)
python3 build.py [OUTDIR] --edition NAME     choose an edition when the project holds several
python3 build.py [OUTDIR] --strict           also fail while any included source is still an unreviewed draft
python3 build.py [OUTDIR] --channel NAME     release (default) leaves out held-back sections; development keeps them
python3 build.py --grades                    print how demanding each group, page and section is, from beginner to advanced
                                             (builds nothing; takes --project, --edition and --channel)
python3 build.py [OUTDIR] --screenshots [DIR]  also screenshot every theme (palette, light and dark) on one example
                                             page into DIR (default docs/screenshots); needs Chrome, Chromium or Edge
"""

import datetime
import hashlib
import json
import pathlib
import shutil
import sys

from . import content, grading, screenshots
from .content import ContentError
from .channels import RELEASE, select as select_channel
from .dictionary import index as dictionary_index
from .help import Book
from .messages import Messages
from .site import Site
from .tree import document as tree_document

ENGINE_ROOT = pathlib.Path(__file__).resolve().parent
ASSETS = ENGINE_ROOT / "assets"

SERVICE_WORKER = """\
// Generated by the phrasebook builder from the files in this release. Do not edit; rerun the build instead.
const CACHE = "phrasebook-{version}";
const FILES = {files};

self.addEventListener("install", (event) => {{
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener("activate", (event) => {{
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
}});

self.addEventListener("fetch", (event) => {{
  if (event.request.method !== "GET") return;
  event.respondWith(
    caches.match(event.request).then((hit) => {{
      if (hit) return hit;
      // A navigation to a URL that was never precached exactly (the bare origin, a trailing slash,
      // an unknown path): fall back to the cached home page rather than fail outright offline.
      if (event.request.mode === "navigate") {{
        return caches.match("index.html").then((home) => home || fetch(event.request));
      }}
      return fetch(event.request);
    }})
  );
}});
"""


def _precache_list(out):
    """Every file the build wrote, as paths relative to out, for the service worker to cache up front."""
    return sorted(p.relative_to(out).as_posix() for p in pathlib.Path(out).rglob("*") if p.is_file() and p.name != "sw.js")


def _cache_version(out, files):
    """A short hash of every precached file's content, so a new release gets a new cache automatically."""
    digest = hashlib.sha256()
    for rel in files:
        digest.update(rel.encode("utf-8") + b"\0" + (pathlib.Path(out) / rel).read_bytes())
    return digest.hexdigest()[:16]


def find_project(projects_dir=None):
    """The project folder to build when none is named: the only folder in `projects_dir`, which is ./content in the
    current directory unless the caller says otherwise (a project's own build.py passes the content/ beside it)."""
    projects_dir = pathlib.Path(projects_dir) if projects_dir else pathlib.Path.cwd() / "content"
    found = sorted(p for p in projects_dir.iterdir() if p.is_dir()) if projects_dir.is_dir() else []
    if len(found) != 1:
        raise ContentError(f"choose a project with --project; found: {', '.join(p.name for p in found) or 'none'}")
    return found[0]


def build(out_dir, project_dir=None, strict=False, edition=None, channel=RELEASE):
    """Validate a project and write its site. Returns the number of pages written.

    Draft sources are reported on stderr; with strict=True they fail the build.
    """
    project = pathlib.Path(project_dir) if project_dir else find_project()
    raw = content.read(project)
    content.validate(raw)
    _, ed = content.pick_edition(raw, edition)
    drafts = content.draft_sources(raw, ed)
    if drafts:
        listing = ", ".join(f"{code}/{sid}" for code, sid in drafts)
        if strict:
            raise ContentError(f"unreviewed draft sources remain: {listing}")
        print(f"warning: unreviewed draft sources: {listing}", file=sys.stderr)
    view = select_channel(raw, channel)
    _, ed = content.pick_edition(view, edition)  # the channel's own edition: it can hold sections back from the About page
    site = Site(view, ed, messages=Messages(view["packs"]), built=datetime.datetime.now(datetime.timezone.utc))
    rendered = site.render_all()
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name, text in rendered.items():
        (out / name).write_text(text, encoding="utf-8")
    (out / "palettes.css").write_text(site.palettes_css(), encoding="utf-8")
    if site.has_varieties():
        (out / "varieties.css").write_text(site.varieties_css(), encoding="utf-8")
    # Framework assets first, then the project's own files, which may add to them or replace them.
    for src in (ASSETS, project / "static"):
        if src.is_dir():
            shutil.copytree(src, out, dirs_exist_ok=True, ignore=shutil.ignore_patterns("__pycache__", ".*"))
    for href in ed.get("stylesheets", []):
        if not href.startswith("https://") and not (out / href).is_file():
            raise ContentError(f"the edition lists the stylesheet {href!r} but the project has no static/{href}")
    for icon in ed.get("icons", []):
        if not (out / icon["src"]).is_file():
            raise ContentError(f"the edition lists the icon {icon['src']!r} but the project has no static/{icon['src']}")
    (out / "manifest.json").write_text(json.dumps(site.manifest(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "tree.json").write_text(json.dumps(tree_document(site), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "dictionary.json").write_text(
        json.dumps(dictionary_index(view, ed), ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    files = _precache_list(out)
    (out / "sw.js").write_text(
        SERVICE_WORKER.format(version=_cache_version(out, files), files=json.dumps(files)), encoding="utf-8"
    )
    return len(rendered)


def take_screenshots(out, view, ed, shots_dir, browser=None):
    """Screenshot every offered palette, light and dark, on one example page: the first topic with a drawing, which shows
    the most of the colours (the accent, the star, text, rules), else the first topic."""
    site = Site(view, ed, messages=Messages(view["packs"]))
    pages = [s for g in site.groups for s in g["pages"]]
    topic = next((s for s in pages if site.skel[s].get("figure")), pages[0])
    labels = {pid: site.palette_label(pid)[0] for pid in site.palette_ids}
    return screenshots.shoot(out, shots_dir, site.palette_ids, f"{topic}.html", labels=labels, browser=browser)


def main(argv=None, projects_dir=None):
    """The command line. `projects_dir` is where to look for the project when --project is not given."""
    argv = list(sys.argv[1:] if argv is None else argv)

    # --screenshots takes an optional folder: the next word, unless that is another option
    shots = None
    if "--screenshots" in argv:
        i = argv.index("--screenshots")
        nxt = argv[i + 1] if i + 1 < len(argv) and not argv[i + 1].startswith("--") else None
        shots = nxt or "docs/screenshots"
        del argv[i : i + (2 if nxt else 1)]

    def option(name):
        if name in argv:
            i = argv.index(name)
            value = argv[i + 1] if i + 1 < len(argv) else None
            del argv[i : i + 2]
            return value
        return None

    edition, project, channel = option("--edition"), option("--project"), option("--channel") or RELEASE
    show_grades = "--grades" in argv
    if show_grades:
        argv.remove("--grades")
    strict = "--strict" in argv
    args = [a for a in argv if not a.startswith("--")]
    out = args[0] if args else "dist"
    if show_grades:  # the grades, for checking by eye; nothing is built
        try:
            raw = content.read(pathlib.Path(project) if project else find_project(projects_dir))
            content.validate(raw)
            view = select_channel(raw, channel)
            _, ed = content.pick_edition(view, edition)
            print(grading.report(grading.grade(view, ed)))
        except ContentError as err:
            sys.exit(f"content error: {err}")
        return
    try:
        project = pathlib.Path(project) if project else find_project(projects_dir)
        n = build(out, project_dir=project, strict=strict, edition=edition, channel=channel)
        raw = select_channel(content.read(project), channel)
        _, ed = content.pick_edition(raw, edition)
        cov = ", ".join(f"{c} {h}/{t}" for c, (h, t) in content.coverage(raw, ed).items())
        helped = ", ".join(f"{c} {h}/{t}" for c, (h, t) in Book.load(raw["packs"]).coverage(ed["languages"]).items())
    except ContentError as err:
        sys.exit(f"content error: {err}")
    print(f"wrote {n} pages to {out} ({channel} channel)")
    print(f"coverage: {cov}")
    print(f"help: {helped}")
    if shots:
        try:
            taken = take_screenshots(out, raw, ed, shots)
        except ContentError as err:
            sys.exit(f"screenshots: {err}")
        print(f"wrote {len(taken)} screenshots to {shots}")
